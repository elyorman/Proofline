import { compileFromFile } from 'json-schema-to-typescript';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const out = new URL('../src/types/', import.meta.url);
await mkdir(out, { recursive: true });
for (const name of ['insight-card', 'cue', 'profile', 'event', 'event-amendment', 'case-file', 'answer', 'live-job']) {
  const source = fileURLToPath(new URL(`../../../docs/${name}.schema.json`, import.meta.url));
  const types = await compileFromFile(source, {
    bannerComment: '/* Generated by pnpm types from the public contracts. Do not edit. */',
    additionalProperties: false,
  });
  await writeFile(new URL(`${name}.ts`, out), types);
}
