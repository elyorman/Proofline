export const catalogs = { en, es };

export function t(locale: Locale, key: string, values: Record<string, string | number> = {}): string {
  const catalog: Record<string, string> = catalogs[locale];
  if (!Object.hasOwn(catalog, key)) throw new Error(`Missing translation: ${locale}.${key}`);
  return catalog[key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function number(locale: Locale, value: number, percent = false): string {
  return new Intl.NumberFormat(locale, percent
    ? { style: 'percent', maximumFractionDigits: 0 }
    : { maximumFractionDigits: 2 }).format(value);
}
