export const catalogs = { en, es };

export function t(locale: Locale, key: string, values: Record<string, string | number> = {}): string {
  const catalog: Record<string, string> = catalogs[locale] ?? catalogs.en;
  const fallback = key.includes('.') ? key.slice(key.indexOf('.') + 1) : key;
  const value = Object.hasOwn(catalog, key) ? catalog[key] : fallback;
  return value.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function metricNumber(locale: Locale, metric: string, value: unknown): string {
  if (typeof value !== 'number' || !Number.isFinite(value)) return String(value ?? '—');
  const percent = ['long_ball_share', 'channel_share_left', 'channel_share_centre', 'channel_share_right'].includes(metric);
  const digits = percent ? 0 : metric === 'sprint_speed' ? 1 : 2;
  const options: Intl.NumberFormatOptions & { roundingMode: 'halfEven' } = {
    minimumFractionDigits: digits, maximumFractionDigits: digits,
    roundingMode: 'halfEven',
    ...(percent ? { style: 'percent' } : {}),
  };
  const formatted = new Intl.NumberFormat(locale, options).format(value);
  return metric === 'sprint_speed' ? `${formatted} km/h` : formatted;
}

export function number(locale: Locale, value: number, percent = false): string {
  return new Intl.NumberFormat(locale, percent
    ? { style: 'percent', maximumFractionDigits: 0 }
    : { maximumFractionDigits: 2 }).format(value);
}
